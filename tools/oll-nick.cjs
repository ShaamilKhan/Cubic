const flat = a => a.trim().replace(/\s+/g, ' ');
const sameTop = s => { const q = Sim.grid(s, 'U').flat(); return q.every(v => v === q[0]); };
// does this algorithm solve the orientation of this case, from some U turn, without disturbing the bottom two layers?
function solves(c, alg) {
  let st = Sim.run(Sim.deRotate(c.setup)), a;
  try { a = Sim.parse(alg); } catch (e) { return false; }   // the model turns the whole cube for y/x/z itself
  for (let j = 0; j < 4; j++) {
    const t = Sim.apply(st.map(x => ({ ...x })), a);
    if (sameTop(t) && Sim.lowerSolved(t)) return true;
    st = Sim.apply(st, Sim.parse('U'));
  }
  return false;
}

const nick = {}, extra = {}, used = new Map(); let bad = 0, added = 0;
for (const [name, alg] of Object.entries(NAMES)) {
  const hits = OLL.cases.filter(c => solves(c, alg));
  if (hits.length !== 1) { console.log(hits.length ? 'AMBIGUOUS' : 'NO MATCH', name, '|', alg, hits.map(h => h.n).join(',')); bad++; continue; }
  const c = hits[0];
  if (used.has(c.n)) { console.log('DUPLICATE', name, 'and', used.get(c.n), '->', c.n); bad++; continue; }
  used.set(c.n, name); nick[c.n] = name;
  if (!c.algs.some(x => flat(x) === flat(alg))) { extra[c.n] = alg; added++; }
}
const missing = OLL.cases.filter(c => !nick[c.n]).map(c => c.n);
console.log('named', Object.keys(nick).length, 'of', OLL.cases.length, 'cases; missing:', missing.join(', ') || 'none', '; extra algorithms added:', added);
if (bad) process.exit(1);
